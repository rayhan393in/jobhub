#!/usr/bin/env python3
"""Render bcs-routine-30day.csv into idempotent SQL for public.routines.

Mirrors the commit phase of src/app/api/admin/routines/import/route.ts exactly:
  - kind: weekly_special iff csv kind contains "weekly"/"সাপ্তাহিক", else daily
  - week_start = ISO Monday of routine_date
  - week_index = floor((week_start - 2024-01-01)/7)+1, clamped to 1..104
  - slot_label = HH:MM–HH:MM from note if present, else Bengali ordinal "স্লট"
  - task_kind  = exam for weekly_special else study
  - title_bn/title_en = topic name, or subject name for subject-level rows
  - target_bn/focus_note_bn = note or NULL
  - status published, created_by = Super Admin profile

Idempotent via the live unique index
  routines_unique_slot_idx (course_id, kind, routine_date, subject_id, topic_id)
  NULLS NOT DISTINCT  →  ON CONFLICT ... DO NOTHING.
"""
from __future__ import annotations

import csv
import datetime as dt
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
CSV_PATH = HERE / "bcs-routine-30day.csv"
SQL_PATH = HERE / "bcs-routine-30day.sql"

COURSE_ID = "599509ae-c4c3-440a-9463-802a4efc7a0c"
CREATED_BY = "6c1dacc3-a6ae-46b2-bdc7-1a2a7cb33615"  # Md Rayhan (Super Admin)

ORDINALS = ["১ম", "২য়", "৩য়", "৪র্থ", "৫ম", "৬ষ্ঠ", "৭ম", "৮ম"]
TIME_RANGE = re.compile(r"\d{1,2}[:.]\d{2}\s*[–\-]\s*\d{1,2}[:.]\d{2}")


def q(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def week_meta(date: dt.date) -> tuple[str, int]:
    monday = date - dt.timedelta(days=date.isoweekday() - 1)
    index = (monday - dt.date(2024, 1, 1)).days // 7 + 1
    return monday.isoformat(), max(1, min(104, index))


def slot_label(slot: int, note: str) -> str:
    match = TIME_RANGE.search(note)
    if match:
        return match.group(0)
    ordinal = ORDINALS[slot - 1] if 1 <= slot <= len(ORDINALS) else f"{slot} নং"
    return f"{ordinal} স্লট"


def main() -> None:
    rows = list(csv.DictReader(CSV_PATH.open(encoding="utf-8-sig")))
    statements: list[str] = []
    for row in rows:
        raw_kind = row.get("kind", "").strip().lower()
        kind = "weekly_special" if ("weekly" in raw_kind or "সাপ্তাহিক" in row.get("kind", "")) else "daily"
        date = dt.date.fromisoformat(row["date"])
        week_start, week_index = week_meta(date)
        subject = row["subject"].strip()
        topic = row["topic"].strip()
        note = row["note"].strip()
        slot = int(row["slot"] or "1")
        minutes = int(row["minutes"] or "60")
        title = topic or subject
        task_kind = "exam" if kind == "weekly_special" else "study"

        topic_sql = (
            "(select t.id from public.topics t"
            " where t.subject_id = s.id and t.title_bn = " + q(topic) + " and t.is_active)"
            if topic
            else "null::uuid"
        )
        note_sql = q(note) if note else "null"

        statements.append(
            "insert into public.routines\n"
            "  (course_id, kind, routine_date, week_start, week_index, slot_label, target_bn,\n"
            "   task_kind, title_bn, title_en, subject_id, topic_id, subtopic_id, minutes,\n"
            "   focus_note_bn, status, created_by)\n"
            "select\n"
            f"  {q(COURSE_ID)}, {q(kind)}, date {q(row['date'])}, date {q(week_start)}, {week_index},\n"
            f"  {q(slot_label(slot, note))}, {note_sql}, {q(task_kind)}, {q(title)}, {q(title)},\n"
            f"  s.id, {topic_sql}, null::uuid, {minutes}, {note_sql}, 'published', {q(CREATED_BY)}\n"
            "from public.subjects s\n"
            f"where s.course_id = {q(COURSE_ID)} and s.title_bn = {q(subject)} and s.is_active\n"
            "on conflict (course_id, kind, routine_date, subject_id, topic_id) do nothing;"
        )

    header = (
        "-- 30-day BCS routine (2026-11-22 → 2026-12-21) for course "
        + COURSE_ID
        + "\n-- Generated by data/bcs-routine/render_sql.py from bcs-routine-30day.csv."
        + "\n-- Idempotent: safe to run more than once (ON CONFLICT DO NOTHING).\n\nbegin;\n\n"
    )
    SQL_PATH.write_text(header + "\n\n".join(statements) + "\n\ncommit;\n", encoding="utf-8")
    print(f"wrote {SQL_PATH.name}: {len(statements)} insert statements")


if __name__ == "__main__":
    main()
